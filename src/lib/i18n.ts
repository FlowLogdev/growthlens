export const SUPPORTED_LOCALES = ["en-US", "es-ES", "pt-BR"] as const;

export type Locale = (typeof SUPPORTED_LOCALES)[number];

export const DEFAULT_LOCALE: Locale = "en-US";
export const LOCALE_COOKIE = "gl_locale";

const SPANISH_COUNTRIES = new Set([
  "AR", "BO", "CL", "CO", "CR", "CU", "DO", "EC", "ES", "GQ", "GT", "HN",
  "MX", "NI", "PA", "PE", "PR", "PY", "SV", "UY", "VE",
]);

const PORTUGUESE_COUNTRIES = new Set(["AO", "BR", "CV", "GW", "MZ", "PT", "ST", "TL"]);

export function normalizeLocale(value?: string | null): Locale | null {
  if (!value) return null;
  const normalized = value.toLowerCase().replace("_", "-");
  if (normalized.startsWith("es")) return "es-ES";
  if (normalized.startsWith("pt")) return "pt-BR";
  if (normalized.startsWith("en")) return "en-US";
  return null;
}

export function localeFromCountry(country?: string | null): Locale | null {
  const code = country?.trim().toUpperCase();
  if (!code) return null;
  if (PORTUGUESE_COUNTRIES.has(code)) return "pt-BR";
  if (SPANISH_COUNTRIES.has(code)) return "es-ES";
  return "en-US";
}

export function detectLocale(country?: string | null, acceptLanguage?: string | null): Locale {
  return localeFromCountry(country) ?? normalizeLocale(acceptLanguage) ?? DEFAULT_LOCALE;
}

